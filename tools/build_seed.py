"""Check the recipe data and generate supabase/seed.sql from supabase/seed/*.json.
Usage (from the repo root): python3 -I tools/build_seed.py
Stops with a clear message if any rule is broken, so bad data never reaches the database."""
import collections, glob, json, re

CATEGORIES = {"main", "soup", "rice", "noodles", "curry", "salad", "snack", "sweet", "drinks"}
NO_PHOTO_YET = {"Khmer Chicken Curry"}  # no free photo found on Wikimedia Commons; app shows a placeholder
OPTIONAL_CUISINES = {"GB"}              # not in the brief; owner still deciding

cuisines = json.load(open("supabase/seed/cuisines.json"))
recipes = [r for p in sorted(glob.glob("supabase/seed/recipes_*.json")) for r in json.load(open(p))]
codes = {c["code"] for c in cuisines}
errors = []
def check(ok, msg):
    if not ok: errors.append(msg)

def sentences(text, end):
    return len([s for s in re.split(end, text) if s.strip()])

titles = collections.Counter(r["title_en"] for r in recipes)
check(not [t for t, n in titles.items() if n > 1], f"duplicate titles: {[t for t, n in titles.items() if n > 1]}")
for r in recipes:
    t = r["title_en"]
    check(r["cuisine"] in codes, f"{t}: unknown cuisine {r['cuisine']}")
    check(r["category"] in CATEGORIES, f"{t}: bad category {r['category']}")
    check(isinstance(r["calories"], int) and 50 <= r["calories"] <= 1500, f"{t}: calories must be a whole number 50-1500")
    check(r["difficulty"] in ("easy", "medium", "hard"), f"{t}: bad difficulty")
    check(r["prep_minutes"] > 0 and r["servings"] > 0, f"{t}: prep_minutes and servings must be positive")
    check(r["title_km"].strip() != "", f"{t}: missing Khmer title")
    check(1 <= sentences(r["description_en"], r"[.!?]") <= 2, f"{t}: English description must be 1-2 sentences")
    check(1 <= sentences(r["description_km"], "។") <= 2, f"{t}: Khmer description must be 1-2 sentences")
    for part in ("ingredients", "steps"):
        en, km = r[part + "_en"], r[part + "_km"]
        check(len(en) > 0 and len(en) == len(km), f"{t}: {part} English/Khmer lists differ in length")
    check(len(r["steps_en"]) <= 8, f"{t}: more than 8 steps")
    check(bool(r.get("image_url")) or t in NO_PHOTO_YET, f"{t}: missing photo")
    check(not r.get("image_url") or r["image_url"].startswith("https://"), f"{t}: photo must use https")
    check(not r.get("image_url") or bool(r.get("image_credit")), f"{t}: photo without credit")

per = collections.Counter(r["cuisine"] for r in recipes)
check(per["KH"] >= 10, f"need at least 10 Cambodian recipes, have {per['KH']}")
for c in codes - {"KH"} - OPTIONAL_CUISINES:
    check(per[c] >= 2, f"cuisine {c} needs at least 2 recipes, has {per[c]}")
if errors:
    raise SystemExit("Seed data has problems:\n- " + "\n- ".join(errors))

def q(v):  # SQL literal
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, list): return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"

C_COLS = ["code", "name_en", "name_km", "adjective_en", "adjective_km", "flag_emoji", "sort_order"]
R_COLS = ["title_en", "title_km", "description_en", "description_km", "calories", "cuisine", "category", "prep_minutes",
          "servings", "difficulty", "is_trending", "popularity", "image_url", "image_credit", "image_page",
          "ingredients_en", "ingredients_km", "steps_en", "steps_km"]
def upsert(table, cols, rows, key):
    values = ",\n".join("(" + ", ".join(q(r.get(c)) for c in cols) + ")" for r in rows)
    sets = ", ".join(f"{c} = excluded.{c}" for c in cols if c != key)
    return f"insert into public.{table} ({', '.join(cols)}) values\n{values}\non conflict ({key}) do update set {sets};\n"

sql = ("-- GENERATED by tools/build_seed.py from supabase/seed/*.json. Edit the JSON files, not this file.\n"
       "-- Safe to run again: existing rows are updated by code / title_en.\n\n"
       + upsert("cuisines", C_COLS, cuisines, "code") + "\n" + upsert("recipes", R_COLS, recipes, "title_en"))
open("supabase/seed.sql", "w").write(sql)
print(f"OK: {len(recipes)} recipes ({per['KH']} Cambodian), {len(cuisines)} cuisines -> supabase/seed.sql")
print("Per cuisine:", dict(sorted(per.items())))
print("No photo yet:", sorted(NO_PHOTO_YET & set(titles)))
